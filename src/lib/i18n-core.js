export function formatTime(value, options = {}, language = getActiveLanguage()) {
  const date = value instanceof Date ? value : new Date(value);

  if (Number.isNaN(date.getTime())) {
    return "-";
  }

  return new Intl.DateTimeFormat(normalizeLanguage(language), {
    hour: "2-digit",
    minute: "2-digit",
    ...options,
  }).format(date);
}

export function formatNumber(value, options = {}, language = getActiveLanguage()) {
  return new Intl.NumberFormat(normalizeLanguage(language), options).format(value || 0);
}

export function compareText(a, b, language = getActiveLanguage()) {
  return String(a || "").localeCompare(String(b || ""), normalizeLanguage(language));
}
