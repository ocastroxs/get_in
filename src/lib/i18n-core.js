const escapeRegExp = (value) => String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

function repairTextEncoding(value) {
  const text = String(value || "");

  if (!/[ÃÂâ]/.test(text)) {
    return text;
  }

  try {
    const bytes = Uint8Array.from(Array.from(text), (character) => character.charCodeAt(0));
    return new TextDecoder("utf-8", { fatal: false }).decode(bytes);
  } catch {
    return text;
  }
}

function getNormalizedIndexMap(value) {
  const text = repairTextEncoding(value);
  let normalized = "";
  const map = [];

  for (let index = 0; index < text.length;) {
    const character = Array.from(text.slice(index))[0];
    const start = index;
    index += character.length;

    const normalizedCharacter = character
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase();

    for (const outputCharacter of normalizedCharacter) {
      normalized += outputCharacter;
      map.push({ start, end: index });
    }
  }

  return { normalized, map, text };
}

function replaceNormalizedFragment(value, source, replacement) {
  const sourceKey = normalizeTextKey(source);

  if (!sourceKey) {
    return { value, changed: false };
  }

  const { normalized, map, text } = getNormalizedIndexMap(value);
  const matchIndex = normalized.indexOf(sourceKey);

  if (matchIndex < 0) {
    return { value, changed: false };
  }

  const start = map[matchIndex]?.start;
  const end = map[matchIndex + sourceKey.length - 1]?.end;

  if (start === undefined || end === undefined) {
    return { value, changed: false };
  }

  return {
    value: `${text.slice(0, start)}${replacement}${text.slice(end)}`,
    changed: true,
  };
}

const normalizeTextKey = (value) =>
  repairTextEncoding(value)
    .trim()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/\s+/g, " ")
    .toLowerCase();

const TEXT_ALIAS_MAP = new Map();

for (const [source, translations] of Object.entries(TEXT_TRANSLATIONS)) {
  TEXT_ALIAS_MAP.set(normalizeTextKey(source), source);
  TEXT_ALIAS_MAP.set(normalizeTextKey(repairTextEncoding(source)), source);

  for (const translatedText of Object.values(translations)) {
    TEXT_ALIAS_MAP.set(normalizeTextKey(translatedText), source);
    TEXT_ALIAS_MAP.set(normalizeTextKey(repairTextEncoding(translatedText)), source);
  }
}

function applyFragmentTranslations(value, language) {
  const normalizedLanguage = normalizeLanguage(language);

  if (normalizedLanguage === DEFAULT_LANGUAGE) {
    return repairTextEncoding(value);
  }

  const repairedValue = repairTextEncoding(value);
  const searchableValue = normalizeTextKey(repairedValue);

  for (const patternTranslation of TEXT_PATTERN_TRANSLATIONS) {
    const patternResult =
      repairedValue.match(patternTranslation.originalPattern || patternTranslation.pattern) ||
      searchableValue.match(patternTranslation.pattern);

    if (patternResult) {
      return patternTranslation[normalizedLanguage].replace(/\$(\d+)/g, (_, index) => patternResult[Number(index)] || "");
    }
  }

  let translatedValue = repairedValue;
  let changed = false;

  const fragments = Object.entries(TEXT_FRAGMENT_TRANSLATIONS).sort((a, b) => b[0].length - a[0].length);

  for (const [source, translations] of fragments) {
    const translation = translations[normalizedLanguage];

    if (!translation) {
      continue;
    }

    const sourcePattern = new RegExp(escapeRegExp(repairTextEncoding(source)), "gi");
    const before = translatedValue;

    if (normalizeTextKey(translatedValue) === normalizeTextKey(source)) {
      return translation;
    }

    translatedValue = translatedValue.replace(sourcePattern, translation);

    if (translatedValue === before) {
      const normalizedReplacement = replaceNormalizedFragment(translatedValue, source, translation);
      translatedValue = normalizedReplacement.value;
    }

    changed = changed || translatedValue !== before;
  }

  return changed ? translatedValue : null;
}

export function normalizeLanguage(language) {
  return SUPPORTED_LANGUAGES.includes(language) ? language : DEFAULT_LANGUAGE;
}

export function getLanguageHtmlTag(language) {
  return normalizeLanguage(language).toLowerCase();
}

export function getActiveLanguage() {
  if (typeof window === "undefined") {
    return DEFAULT_LANGUAGE;
  }

  try {
    const rawPreferences = localStorage.getItem("getin_user_preferences");
    const preferences = rawPreferences ? JSON.parse(rawPreferences) : null;
    return normalizeLanguage(preferences?.idioma);
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function setDocumentLanguage(language) {
  if (typeof document === "undefined") {
    return;
  }

  document.documentElement.lang = getLanguageHtmlTag(language);
  document.documentElement.dataset.language = normalizeLanguage(language);
}

export function interpolate(message, params = {}) {
  return String(message || "").replace(/\{\{(\w+)\}\}/g, (_, key) => params[key] ?? "");
}

export function translateText(value, language = getActiveLanguage(), params = {}) {
  const normalizedLanguage = normalizeLanguage(language);
  const raw = String(value ?? "");
  const trimmed = raw.trim();

  if (!trimmed) {
    return raw;
  }

  const prefix = raw.match(/^\s*/)?.[0] || "";
  const suffix = raw.match(/\s*$/)?.[0] || "";
  const repairedTrimmed = repairTextEncoding(trimmed);
  const canonical = TEXT_ALIAS_MAP.get(normalizeTextKey(trimmed)) || TEXT_ALIAS_MAP.get(normalizeTextKey(repairedTrimmed));
  const exactTranslation =
    canonical &&
    (normalizedLanguage === DEFAULT_LANGUAGE
      ? repairTextEncoding(canonical)
      : TEXT_TRANSLATIONS[canonical]?.[normalizedLanguage]);
  const translation =
    exactTranslation ||
    applyFragmentTranslations(repairedTrimmed, normalizedLanguage) ||
    repairedTrimmed;

  return `${prefix}${interpolate(translation, params)}${suffix}`;
}

export function t(key, params = {}, language = getActiveLanguage()) {
  const normalizedLanguage = normalizeLanguage(language);
  const message = MESSAGE_TRANSLATIONS[key]?.[normalizedLanguage];

  if (message) {
    return interpolate(message, params);
  }

  return translateText(key, normalizedLanguage, params);
}

export function formatDateTime(value, options = {}, language = getActiveLanguage()) {
  const date = value instanceof Date ? value : new Date(value);

  if (Number.isNaN(date.getTime())) {
    return "-";
  }

  return new Intl.DateTimeFormat(normalizeLanguage(language), {
    dateStyle: "short",
    timeStyle: "short",
    ...options,
  }).format(date);
}

